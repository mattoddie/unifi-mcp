/**
 * Generates docs/tools.md from the registered tools and prompts, so the
 * reference can't drift from the code. Run with `npm run docs:tools`;
 * `npm run docs:check` fails when the committed file is out of date.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { Client } from "@modelcontextprotocol/sdk/client/index.js";
import { InMemoryTransport } from "@modelcontextprotocol/sdk/inMemory.js";
import { TOOLSETS, type Toolset } from "../config.js";
import { createServer } from "../server.js";
import { UnifiClient } from "../unifi/client.js";

const TOOLSET_INFO: Record<Toolset, string> = {
  overview: "Sites, controller information and site health.",
  devices: "UniFi devices (gateways, switches, access points, PDUs): status, firmware, radios, adoption and maintenance.",
  clients: "Connected and known clients: lookup, blocking, reconnecting and naming.",
  switching: "Switch ports and port profiles, including PoE.",
  wifi: "WiFi networks (WLANs) and join QR codes.",
  networks: "Networks/VLANs, WAN links, local DNS records, bandwidth profiles and dynamic DNS.",
  firewall: "Port forwards, legacy firewall rules and groups, zone-based firewall policies and zones, and traffic rules.",
  routing: "Static routes and policy-based traffic routes.",
  security: "Threat management (IDS/IPS), country blocking and content filtering.",
  vpn: "VPN servers and site-to-site VPNs, RADIUS profiles and RADIUS accounts.",
  hotspot: "Hotspot vouchers, operators, guest authorization and the guest portal.",
  monitoring: "Events, alarms, traffic and DPI statistics, speed tests, logs and dashboards.",
  admin: "Site settings, administrators, backups, controller updates and site management.",
  raw: "A raw API escape hatch for anything the other tools don't cover. It is limited to GET requests unless writes are enabled.",
};

interface JsonSchema {
  type?: string | string[];
  description?: string;
  enum?: unknown[];
  const?: unknown;
  items?: JsonSchema;
  anyOf?: JsonSchema[];
  properties?: Record<string, JsonSchema>;
  required?: string[];
  default?: unknown;
  minimum?: number;
  maximum?: number;
}

function typeOf(s: JsonSchema): string {
  if (s.const !== undefined) return `\`${JSON.stringify(s.const)}\``;
  if (s.enum) return s.enum.map((v) => `\`${JSON.stringify(v)}\``).join(" | ");
  if (s.anyOf) return s.anyOf.map(typeOf).join(" | ");
  if (s.type === "array") {
    const item = s.items ? typeOf(s.items) : "any";
    return item.includes(" | ") ? `(${item})[]` : `${item}[]`;
  }
  if (Array.isArray(s.type)) return s.type.join(" | ");
  return s.type ?? "any";
}

function cell(text: string): string {
  return text.replace(/\|/g, "\\|").replace(/\s*\n\s*/g, " ");
}


async function main(): Promise<void> {
  // A client that is never used: listing tools doesn't touch the controller.
  const unifi = new UnifiClient({
    url: "https://unifi.invalid",
    apiKey: "unused",
    site: "default",
    verifySsl: false,
    controllerType: "unifi-os",
    timeoutMs: 1000,
  });
  const all = { allowWrites: true, allowDeletes: true, toolsets: new Set(TOOLSETS) };
  const toolsetOf = new Map<string, Toolset>();
  for (const ts of TOOLSETS) {
    const tools = await list({ ...all, toolsets: new Set([ts]) });
    for (const t of tools.tools) toolsetOf.set(t.name, ts);
  }
  const deletes = new Set((await list(all)).tools.map((t) => t.name));
  const noDeletes = new Set((await list({ ...all, allowDeletes: false })).tools.map((t) => t.name));
  const reads = new Set((await list({ ...all, allowWrites: false, allowDeletes: false })).tools.map((t) => t.name));
  const { tools, prompts } = await list(all);

  async function list(options: typeof all) {
    const server = createServer(unifi, options);
    const [a, b] = InMemoryTransport.createLinkedPair();
    await server.connect(a);
    const mcp = new Client({ name: "gen-docs", version: "0" });
    await mcp.connect(b);
    const result = { tools: (await mcp.listTools()).tools, prompts: (await mcp.listPrompts()).prompts };
    await mcp.close();
    return result;
  }

  const gate = (name: string) => (reads.has(name) ? "read" : noDeletes.has(name) ? "write" : deletes.has(name) ? "delete" : "?");
  const count = (g: string) => tools.filter((t) => gate(t.name) === g).length;

  const out: string[] = [];
  out.push(
    "# Tool reference",
    "",
    "<!-- Generated by `npm run docs:tools` from the tool definitions. Do not edit by hand. -->",
    "",
    `unifi-mcp has **${tools.length} tools** in **${TOOLSETS.length} toolsets**: ${count("read")} read, ${count("write")} write and ${count("delete")} delete. It also has **${prompts.length} prompts**.`,
    "",
    "Each tool is labelled with the setting it needs:",
    "",
    "| Label | Registered when |",
    "|---|---|",
    "| 🟢 read | Always |",
    "| 🟠 write | `UNIFI_ALLOW_WRITES=true` |",
    "| 🔴 delete | `UNIFI_ALLOW_WRITES=true` and `UNIFI_ALLOW_DELETES=true` |",
    "",
    "Every tool also needs its toolset to be enabled in `UNIFI_TOOLSETS`, which enables all toolsets by default. Most tools take an optional `site` argument, which defaults to `UNIFI_SITE`.",
    "",
    "## Contents",
    "",
    ...TOOLSETS.map((ts) => `- [\`${ts}\`](#${ts}): ${TOOLSET_INFO[ts]}`),
    "- [Prompts](#prompts)",
    "",
  );

  const badge: Record<string, string> = { read: "🟢 read", write: "🟠 write", delete: "🔴 delete" };
  for (const ts of TOOLSETS) {
    out.push(`## ${ts}`, "", TOOLSET_INFO[ts], "");
    const inSet = tools.filter((t) => toolsetOf.get(t.name) === ts);
    out.push("| Tool | Access | Summary |", "|---|---|---|");
    for (const t of inSet) out.push(`| [\`${t.name}\`](#${t.name}) | ${badge[gate(t.name)]} | ${cell(t.title ?? t.annotations?.title ?? "")} |`);
    out.push("");
    for (const t of inSet) {
      out.push(`### ${t.name}`, "", `${badge[gate(t.name)]}${t.annotations?.destructiveHint ? " · destructive" : ""}`, "", t.description ?? "", "");
      const schema = t.inputSchema as JsonSchema;
      const props = Object.entries(schema.properties ?? {});
      if (props.length === 0) {
        out.push("_No arguments._", "");
        continue;
      }
      const required = new Set(schema.required ?? []);
      out.push("| Argument | Type | Required | Description |", "|---|---|---|---|");
      for (const [name, p] of props) {
        let desc = p.description ?? "";
        if (p.default !== undefined) desc += `${desc ? " " : ""}Default: \`${JSON.stringify(p.default)}\`.`;
        out.push(`| \`${name}\` | ${cell(typeOf(p))} | ${required.has(name) ? "yes" : ""} | ${cell(desc)} |`);
      }
      out.push("");
    }
  }

  out.push("## Prompts", "", "Prompts are ready-made requests that tell the model which tools to call and what to report. In Claude Code they appear as slash commands, such as `/mcp__unifi__network_health_check`.", "");
  for (const p of prompts) {
    out.push(`### ${p.name}`, "", p.description ?? "", "");
    if (p.arguments?.length) {
      out.push("| Argument | Required | Description |", "|---|---|---|");
      for (const a of p.arguments) out.push(`| \`${a.name}\` | ${a.required ? "yes" : ""} | ${cell(a.description ?? "")} |`);
      out.push("");
    }
  }

  const text = out.join("\n").replace(/\n{3,}/g, "\n\n");
  const target = "docs/tools.md";
  if (process.argv.includes("--check")) {
    let current = "";
    try {
      current = readFileSync(target, "utf8");
    } catch {}
    if (current !== text) {
      console.error(`${target} is out of date. Run \`npm run docs:tools\` and commit the result.`);
      process.exit(1);
    }
    console.log(`${target} is up to date.`);
  } else {
    writeFileSync(target, text);
    console.log(`Wrote ${target} (${tools.length} tools, ${prompts.length} prompts).`);
  }
  await unifi.close();
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
